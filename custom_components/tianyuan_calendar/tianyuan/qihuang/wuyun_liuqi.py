    五运偏盛偏衰 = 五运六气映射.get("五运偏盛偏衰", {})
    六气偏盛偏衰 = 五运六气映射.get("六气偏盛偏衰", {})
    六步主气表 = 五运六气映射.get("六步主气", [])               # 步名列表
    六气轮转表 = 五运六气映射.get("六气轮转", [])               # 三阴三阳固定次序
    六气属性表 = 五运六气映射.get("六气属性", {})
    五行关系表 = 五运六气映射.get("五行关系", {})
    气机病机表 = 五运六气映射.get("气机病机", {})
