    @staticmethod
    def 全量计算类(农历) -> dict:
        年干 = 农历.getYearGanExact()
        年支 = 农历.getYearZhiExact()
        缓存键 = f"{年干}{年支}"

        if 缓存键 in 五运六气类._年度缓存:
            年度数据 = 五运六气类._年度缓存[缓存键]
        else:
            年度数据 = {
                "年五运数据": 五运六气类.年五运类法(年干),
                "年六气数据": 五运六气类.年六气类法(年支),
                "六步运气数据_全量": 五运六气类.六步运气数据类法(年干, 年支),
                "年度总览数据": 五运六气类.年度总览类(年干, 年支)
            }
            五运六气类._年度缓存[缓存键] = 年度数据

        # 取出当前步
        全量六步 = 五运六气类.六步运气数据类法(年干, 年支)
        当前索引 = 五运六气类.获取当前步序法(农历)
        当前步 = 全量六步[当前索引]

        return {
            "年五运数据": 年度数据["年五运数据"],
            "年六气数据": 年度数据["年六气数据"],
            "六步运气数据": {
                "state": 当前步["state"],
                "attributes": 当前步["attributes"]
            },
            "年度总览数据": 年度数据["年度总览数据"]
        }