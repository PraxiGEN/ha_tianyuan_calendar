    # ========= 六步客气（经典司天在泉法） =========
    @staticmethod
    def 获取六步客气法(年支: str) -> list:
        """
        按年支定司天（三之气）→ 在泉（终之气），
        依据三阴三阳固定次序推算六步客气。
        """
        司天 = 五运六气类.获取六气法(年支)
        在泉 = 五运六气类.获取在泉法(年支)
        顺序 = 五运六气类.三阴三阳顺序表

        if 司天 not in 顺序 or 在泉 not in 顺序:
            return [(步, "未知") for 步 in 五运六气类.六步主气表]

        # 以三之气为司天，逆推初之气、二之气
        司天位置 = 顺序.index(司天)
        # 四之气：司天后一位
        四气位置 = (司天位置 + 1) % 6
        # 五之气：司天后两位
        五气位置 = (司天位置 + 2) % 6
        # 终之气（在泉）应位于司天后三位（对化关系），校验一下
        终气位置 = (司天位置 + 3) % 6
        if 顺序[终气位置] != 在泉:
            # 数据异常时回退为直接使用轮转表
            终气位置 = 顺序.index(在泉)
        # 初之气：在泉后一位
        初气位置 = (终气位置 + 1) % 6
        # 二之气：在泉后两位
        二气位置 = (终气位置 + 2) % 6

        # 六步客气序列：初、二、三、四、五、终
        客气序列 = [
            顺序[初气位置],
            顺序[二气位置],
            顺序[司天位置],
            顺序[四气位置],
            顺序[五气位置],
            顺序[终气位置]
        ]
        return list(zip(五运六气类.六步主气表, 客气序列))

